const DialogueScript& ExtraDialogue(DialogueSection section,ShotType shot) {
    const bool marisa=shot==ShotType::MagicMissile||shot==ShotType::IllusionLaser;
    if(!marisa&&shot!=ShotType::HomingAmulet&&shot!=ShotType::Needle)throw std::invalid_argument("Invalid Extra dialogue shot");
    switch(section) {
        case DialogueSection::MainBefore:return marisa?kMarisaMainBefore:kReimuMainBefore;
        case DialogueSection::MainAfter:return marisa?kMarisaMainAfter:kReimuMainAfter;
        case DialogueSection::Midboss:return marisa?kMarisaMidboss:kReimuMidboss;
        case DialogueSection::EncoreBefore:return marisa?kMarisaEncoreBefore:kReimuEncoreBefore;
        case DialogueSection::EncoreAfter:return marisa?kMarisaEncoreAfter:kReimuEncoreAfter;
        case DialogueSection::EncoreInterlude:return marisa?kMarisaEncoreInterlude:kReimuEncoreInterlude;
    }
    throw std::invalid_argument("Invalid Extra dialogue section");
}
